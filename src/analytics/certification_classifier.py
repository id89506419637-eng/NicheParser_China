@dataclass
class CertificationHint:
    level: str = "low"           # low | medium | high | unknown
    label: str = ""              # короткое человеческое имя барьера
    description: str = ""        # 1 предложение — что делать
    icon: str = "🟢"

    @property
    def is_high(self) -> bool:
        return self.level == "high"

    def as_dict(self) -> dict:
        return {
            "level": self.level, "label": self.label,
            "description": self.description, "icon": self.icon,
        }


def classify_certification(
    title: str = "",
    category: str = "",
) -> CertificationHint:
    """
    Грубо определить уровень регуляторного барьера в РФ по названию + категории.
    Не заменяет юриста/сертификационный центр — только сигнальная подсказка.
    """
    text = f"{title or ''} {category or ''}".lower()

    # 1) Высокий барьер — проверяем первым, самое серьёзное
    for kw in _KEYWORDS_HIGH:
        if kw in text:
            return CertificationHint(
                level="high",
                label="Лицензия / спецразрешение",
                description=(
                    "Категория регулируется профильным госорганом (Росздрав, "
                    "ФСТЭК, МВД, Ростехнадзор и т.п.). Ввоз/продажа без "
                    "лицензии запрещены. Уточни у сертиф. центра ДО закупки."
                ),
                icon="🔴",
            )

    # 2) Двойное назначение — дополнительный триггер (тоже high)
    for kw in _KEYWORDS_DUAL_USE_HINTS:
        if kw in text:
            return CertificationHint(
                level="high",
                label="⚠ Двойное назначение",
                description=(
                    "Возможно попадание в перечень товаров двойного назначения "
                    "(ФСТЭК). Нужен паспорт экспортного контроля. Уточни у "
                    "профильного брокера ДО закупки."
                ),
                icon="🔴",
            )

    # 3) Средний барьер — сертификат ТР ТС/ЕАС
    for kw in _KEYWORDS_MEDIUM:
        if kw in text:
            return CertificationHint(
                level="medium",
                label="Сертификат ЕАС / ТР ТС",
                description=(
                    "Обязательный сертификат соответствия по техрегламенту "
                    "ЕАЭС. Стоимость 100-300к ₽, срок 1-3 месяца, орган по "
                    "сертификации подберёт по коду ТН ВЭД."
                ),
                icon="🟡",
            )

    # 4) Дефолт — низкий барьер (декларация ТР ТС)
    return CertificationHint(
        level="low",
        label="Декларация ТР ТС",
        description=(
            "Скорее всего достаточно декларации соответствия — 5-15к ₽ и "
            "2-4 недели через испытательную лабораторию. Уточни у брокера "
            "конкретный ТР ТС по коду ТН ВЭД."
        ),
        icon="🟢",
    )
